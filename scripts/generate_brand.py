"""Transcribe the checked-in Sevra vectors to native paths, without a font runtime.

This intentionally accepts only the primitives used by the approved assets.
Run with --check to verify the committed Swift output; no rendering dependency.
"""
from pathlib import Path
import argparse
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
NUMBER = r"[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?"


def transformed(value, transform):
    x, y = value
    sx, sy, tx, ty = transform
    return x * sx + tx, y * sy + ty


def point(value, transform):
    x, y = transformed(value, transform)
    return f"CGPoint(x: {x:g}, y: {y:g})"


def compose(parent, expression):
    sx, sy, tx, ty = parent
    for name, arguments in re.findall(r"(\w+)\(([^)]*)\)", expression):
        values = [float(v) for v in re.findall(NUMBER, arguments)]
        if name == "translate" and len(values) in (1, 2):
            tx += values[0] * sx
            ty += (values[1] if len(values) == 2 else 0) * sy
        elif name == "scale" and len(values) in (1, 2):
            sx *= values[0]
            sy *= values[-1]
        else:
            raise ValueError(f"Unsupported transform: {name}")
    return sx, sy, tx, ty


def paths(node, transform=(1, 1, 0, 0)):
    transform = compose(transform, node.get("transform", ""))
    name = node.tag.rsplit("}", 1)[-1]
    lines = []
    if name in {"svg", "g"}:
        for child in node:
            lines += paths(child, transform)
    elif name == "path":
        tokens = re.findall(r"[A-Za-z]|" + NUMBER, node.attrib["d"])
        index, current = 0, (0, 0)
        while index < len(tokens):
            command = tokens[index]
            count = {"M": 2, "L": 2, "H": 1, "V": 1, "Q": 4, "C": 6, "Z": 0}.get(command)
            if count is None:
                raise ValueError(f"Unsupported path command: {command}")
            values = list(map(float, tokens[index + 1:index + 1 + count]))
            index += 1 + count
            if command == "Z":
                lines.append("p.closeSubpath()")
                continue
            if command == "H":
                values = [values[0], current[1]]
            if command == "V":
                values = [current[0], values[0]]
            current = tuple(values[-2:])
            end = point(current, transform)
            if command == "M":
                lines.append(f"p.move(to: {end})")
            elif command in {"L", "H", "V"}:
                lines.append(f"p.addLine(to: {end})")
            elif command == "Q":
                lines.append(f"p.addQuadCurve(to: {end}, control: {point(values[:2], transform)})")
            elif command == "C":
                lines.append(f"p.addCurve(to: {end}, control1: {point(values[:2], transform)}, control2: {point(values[2:4], transform)})")
    elif name == "circle":
        cx, cy, radius = (float(node.attrib[k]) for k in ("cx", "cy", "r"))
        x, y = transformed((cx - radius, cy - radius), transform)
        lines.append(f"p.addEllipse(in: CGRect(x: {x:g}, y: {y:g}, width: {2 * radius * transform[0]:g}, height: {2 * radius * transform[1]:g}))")
    elif name != "title":
        raise ValueError(f"Unsupported SVG element: {name}")
    return lines


def generate():
    output = "// Generated by scripts/generate_brand.py from Resources/Brand. Do not redraw.\nimport SwiftUI\n\n"
    for filename, typename in [("sevra-mark.svg", "ObserverMark"), ("sevra-wordmark.svg", "SevraWordmark")]:
        svg = ET.parse(ROOT / "Resources/Brand" / filename).getroot()
        x, y, width, height = map(float, svg.attrib["viewBox"].split())
        assert x == 0 and y == 0
        output += f"struct {typename}: Shape {{\n  func path(in rect: CGRect) -> Path {{\n    var p = Path()\n"
        output += "".join("    " + line + "\n" for line in paths(svg))
        output += f"""    let scale = min(rect.width / {width:g}, rect.height / {height:g})
    return p.applying(CGAffineTransform(
      a: scale, b: 0, c: 0, d: scale,
      tx: rect.midX - {width:g} * scale / 2, ty: rect.midY - {height:g} * scale / 2))
  }}
}}

"""
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "Sources/SevraApp/BrandShapes.swift"
    generated = generate()
    if args.check:
        if not target.exists() or target.read_text() != generated:
            raise SystemExit("Native brand paths need regeneration: python3 scripts/generate_brand.py")
        print("Native brand paths match the approved source vectors.")
    else:
        target.write_text(generated)
